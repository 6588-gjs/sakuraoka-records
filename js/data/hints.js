/* ==========================================================================
 * data/hints.js — 提示系统（按当前进度动态生成「当前目标 + 行动建议」）
 * 设计目的：
 *   1. 玩家随时知道下一步要做什么（降低卡关，利于 TapTap 审核体验）；
 *   2. 提示不直接剧透，最后一条放在「含答案」折叠区内。
 * ========================================================================== */
(function () {
  'use strict';

  function state() {
    return SK.core.state.get();
  }

  function has(id) {
    return state().evidence.indexOf(id) >= 0;
  }

  function baseUnderCount() {
    const list = SK.data.clues.BASE_UNDER_EVIDENCE;
    return list.filter(function (id) {
      return has(id);
    }).length;
  }

  /* 判断当前处于第几幕 */
  function currentAct() {
    const st = state();
    if (st.page.indexOf('a1_') === 0) return 1;
    if (st.page.indexOf('a2_') === 0) return 2;
    if (st.page.indexOf('a3_') === 0 || st.page === 'board') return st.act || 3;
    return st.act || 1;
  }

  /* ------------------------------------------------------------------------
   * 第一幕提示
   * ---------------------------------------------------------------------- */
  function act1Hint() {
    const st = state();
    const lv = st.a1Level;
    if (lv === 0) {
      return {
        act: '第一幕 / 2024 — 記録室',
        goal: '进入「記録室デジタルアーカイブ」，用学生账号登录。',
        steps: [
          '在官网里翻找：网站地图（サイトマップ）最下方有一行小字「関係者専用」，那里就是档案室的入口。',
          '登录需要 ID 与密码：查看「図書委員会」可知学生 ID 规则（s＋学号），查看「情報システム管理規程」可知密码规则（名字罗马字＋学号）。',
          '也可以用「卒業アルバム」确认真实姓名与学号，再登录。'
        ],
        spoiler: '学生账号：s031 / karen031。登录后先读完所有学生权限的文档。'
      };
    }
    if (lv === 1 && !has('c_erased')) {
      return {
        act: '第一幕 / 2024 — 記録室',
        goal: '收集学生记录，在推理板上合成「記録は意図的に消された」。',
        steps: [
          '打开出席簿（第31号的存在）、集合写真（照片里的第31人）、学籍簿（只有30人）、图书借阅卡（樱井花怜的名字）。',
          '点击工具栏的「推理」或页面上的「推理ボード」，进入推理板。',
          '在推理板上点选两张相关证据，再点「推理」进行合成。想想：什么证据能证明「第31号确实存在」？什么证据能证明「记录被有意抹消」？'
        ],
        spoiler: '合成顺序：第31号 + 照片 → 「第31号确实存在」；再与学籍簿 → 「记录是有意被抹消的」。完成后教职员登录会解锁。'
      };
    }
    if (lv === 1 && has('c_erased')) {
      return {
        act: '第一幕 / 2024 — 記録室',
        goal: '登出学生账号，改用教职员账号登录。',
        steps: [
          '回到「記録室デジタルアーカイブ」登录页（档案库右上角的登出按钮）。',
          '教职员 ID 为姓氏罗马字，初始密码为校花罗马字＋着任年份，这些都能在「情報システム管理規程」与「教職員紹介」里找到线索。',
          '登录后可以查看职员的机密文档。'
        ],
        spoiler: '教职员账号：katsuragi / sakura2002。'
      };
    }
    if (lv === 2 && !st.solved.a1code) {
      return {
        act: '第一幕 / 2024 — 記録室',
        goal: '解除档案库里的「封印ファイル」。',
        steps: [
          '先在教职员权限下读完「職員会議メモ」与「鍵管理簿」，收集两条关键记录。',
          '档案库侧栏会提示存在封印文件，点击「解除する」。',
          '暗号是旧图书室内锁被更换的日期（月日 4 位），这个日期写在「鍵管理簿」里。'
        ],
        spoiler: '封印暗号：0413（4 月 13 日）。解除后可读到「情報システム管理者メモ」。'
      };
    }
    if (lv === 2 && st.solved.a1code && !has('c_conspiracy')) {
      return {
        act: '第一幕 / 2024 — 記録室',
        goal: '把换锁记录与职员会议指示合成，证明学校上下合谋隐瞒。',
        steps: [
          '确认已读过「職員会議メモ」（按转校处理）与「鍵管理簿」（应葛城要求换锁）。',
          '前往推理板，把这两条证据合成。'
        ],
        spoiler: '合成：内锁更换记录 + 职员会议指示 → 「学校上下合谋隐瞒」。之后 1989 年旧校报可读。'
      };
    }
    return {
      act: '第一幕 / 2024 — 記録室',
      goal: '打开 1989 年旧校报，追溯记忆进入第二幕。',
      steps: [
        '从档案库侧栏的提示进入「旧校報 昭和64年3月号」，或从站点导航进入。',
        '满足条件后页面会出现「記憶を辿る」按钮。',
        '点击按钮进入 1989 年的校报编辑室。'
      ],
      spoiler: '如果按钮没出现：确认已获得「学校上下合谋隐瞒」并解除封印文件（0413）。'
    };
  }

  /* ------------------------------------------------------------------------
   * 第二幕提示
   * ---------------------------------------------------------------------- */
  function act2Hint() {
    const st = state();
    if (!st.solved.a2witness) {
      return {
        act: '第二幕 / 1989 — 校報編集室',
        goal: '在服务器终端完成「照合クエリ 1/2」：当天在旧图书室的人是谁？',
        steps: [
          '查看「当番表」：当天 16:00 诗织前往旧图书室，16:30 葛城前往，17:00 上锁，17:10 发生事故。',
          '查看「証言メモ」：学生听到惨叫、看到葛城离开，而教头声称自己不在场。',
          '回到「サーバ端末」，选择符合值班表的组合。'
        ],
        spoiler: '正确答案：藤宮詩織と葛城修（诗人与葛城修）。'
      };
    }
    if (!st.solved.a2proof) {
      return {
        act: '第二幕 / 1989 — 校報編集室',
        goal: '完成「照合クエリ 2/2」：哪份记录能证明学校隐瞒了事故？',
        steps: [
          '查看「修繕記録 旧図書室」：内锁损坏、现场有争斗痕迹、由葛城委托更换。',
          '再想想：如果学校声称是转校，那么修缮记录就是隐瞒行为的物证。',
          '在终端选择对应的记录。'
        ],
        spoiler: '正确答案：修繕記録 旧図書室。'
      };
    }
    if (!st.solved.a2upload) {
      return {
        act: '第二幕 / 1989 — 校報編集室',
        goal: '根据诗织的日记推导上传密码，完成最终稿上传。',
        steps: [
          '读「詩織の日記」：密码是「姓氏罗马字小写＋那天日期的月日 4 位」。',
          '日期就是事故发生的日期，可在当番表与修缮记录中确认（3 月 12 日）。',
          '在终端输入密码并点击 UPLOAD。'
        ],
        spoiler: '上传密码：fujimiya0312（fujimiya + 0312）。'
      };
    }
    return {
      act: '第二幕 / 1989 — 校報編集室',
      goal: '上传完成，前往第三幕。',
      steps: [
        '阅读上传完成后的独白。',
        '点击「三周目へ」进入 2024 年的表 / 里网页。'
      ],
      spoiler: '第三幕的关键是「表/裏」切换按钮；里网页会逐步给出 6 件核心证据。'
    };
  }

  /* ------------------------------------------------------------------------
   * 第三幕提示
   * ---------------------------------------------------------------------- */
  function act3Hint() {
    const st = state();
    const underCount = baseUnderCount();
    const hasKiller = has('e_killer');
    const hasFinal = has('e_final');
    const hasRhyme = has('e_rhyme');

    if (underCount < 5) {
      return {
        act: '第三幕 / 2024 — 100%正直なサイト',
        goal: '切换到里网页，收集 5 件被隐藏的事实（当前 ' + underCount + ' / 5）。',
        steps: [
          '点击工具栏的「裏/表」按钮，或页面上的模式按钮，切换到里网页。',
          '在里网页依次查看：1989 年旧校报、2002 年学校通讯、教职员介绍、图书委员会、记录室。',
          '每看一页都会获得一件里页证据；你的名字也会被削去一点，这是设定，不会真的影响存档。',
          '最后去「記録室」的里网页，那里有隐藏页面的入口。'
        ],
        spoiler: '5 件里页证据：藤宫诗织死亡记录、樱井花怜死亡记录、葛城修犯罪记录、花怜的残响、拓也的抹除日志。'
      };
    }
    if (!hasKiller || !hasFinal) {
      return {
        act: '第三幕 / 2024 — 100%正直なサイト',
        goal: '在推理板上把里页证据连起来，取得「最終報告の証拠」。',
        steps: [
          '打开推理板，先把「1989 年死亡记录」与「2002 年死亡记录」合成，得到两起事件同构的证据。',
          '再与葛城修的犯罪记录合成，得到「葛城修是两起事件凶手」。',
          '把「抹除日志」与「花怜的残响」合成，得到恢复拓也名字的方法。',
          '最后把「凶手」与「恢复方法」合成，得到最终报告证据。'
        ],
        spoiler: '配方：e_shiori+e_karen → e_pattern；e_pattern+e_katsuragi → e_killer；e_log+e_message → e_rescue；e_killer+e_rescue → e_final。'
      };
    }
    if (!st.ritualUnlocked) {
      return {
        act: '第三幕 / 2024 — 100%正直なサイト',
        goal: '打开隐藏页面，解开诅咒仪式的暗号。',
        steps: [
          '在里网页进入「記録室」，页面下方有「隠しページを開く」按钮。',
          '暗号规则：两人的死亡月日，按时间顺序排列。1989 年 3 月 12 日、2002 年 4 月 12 日。',
          '输入 8 位数字。'
        ],
        spoiler: '仪式暗号：03120412（03/12 与 04/12 依次排列）。'
      };
    }
    if (!hasRhyme) {
      return {
        act: '第三幕 / 2024 — 100%正直なサイト',
        goal: '在里网页读童谣的原曲，回答「叫到第几遍名字会回来」。',
        steps: [
          '切换到里网页，打开导航里的「童謡」。',
          '原曲歌词里有一句「四度呼べば名が返る」。',
          '选择对应选项。'
        ],
        spoiler: '正确答案：四度（第四遍）。'
      };
    }
    return {
      act: '第三幕 / 2024 — 100%正直なサイト',
      goal: '前往「最終選択」，做出你的最终选择。',
      steps: [
        '现在已满足全部结局的条件：最终报告证据、诅咒仪式、童谣原文、6 件里页证据都已齐备。',
        '在导航中打开「最終選択」。',
        '四个结局分别是：向警方报案 / 发动诅咒 / 公开真相 / 什么都不做。',
        '选择后达成结局，并会自动记录到「结局鉴赏」。'
      ],
      spoiler: '推荐先看「向警方报案」与「公开真相」，再收集「发动诅咒」「什么都不做」，即可 4 结局全收集。'
    };
  }

  /* ------------------------------------------------------------------------
   * 对外接口
   * ---------------------------------------------------------------------- */
  SK.data.hints = {
    build: function () {
      const act = currentAct();
      if (act === 1) return act1Hint();
      if (act === 2) return act2Hint();
      return act3Hint();
    },
    /* 供测试/调试读取当前幕 */
    currentAct: currentAct
  };
})();
